"""Generate runtime rig profiles from the prepared additional-mech manifests."""
import json
from pathlib import Path
root = Path(__file__).resolve().parents[1]
models = json.loads((root / 'Data/additional-mech-models.json').read_text())
lines = ['// Generated by scripts/generate-additional-rigs.py from source model manifests.',
         'using Godot;', '', 'namespace Mech;', '', 'public partial class MechModel', '{',
         '    private sealed record AdditionalRig(string Chassis, RigProfile Rig);',
         '    private static readonly Dictionary<string, AdditionalRig> AdditionalRigs = new()', '    {']

def f(value):
    return f'{value:.7f}f'
def vec(value):
    return 'new(' + ', '.join(f(v) for v in value) + ')'

for model in models:
    manifest = json.loads((root / 'Assets/Models' / (model['chassis'] + '.json')).read_text())
    rig = manifest['rig']
    lines.append(f'        ["{model["id"]}"] = new("{model["chassis"]}", new({f(rig["waist"])}, {vec(rig["hip"])}, {vec(rig["knee"])},')
    lines.append(f'            {vec(rig["ankle"])}, {vec(rig["shoulder"])}, new(BodyDrop: .08f, RunDrop: .045f, LeftArmSwing: .04f, RightArmSwing: .04f))),')
lines.extend(['    };', '}', ''])
(root / 'Scripts/AdditionalMechRigs.cs').write_text('\n'.join(lines))
