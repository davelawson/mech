"""Generate the runtime prepared-model table from catalog chassis, model manifests and gait tuning."""
import json
from pathlib import Path
root = Path(__file__).resolve().parents[1]
catalog = json.loads((root / 'Data/mech-catalog.json').read_text())
gaits = json.loads((root / 'Data/mech-gaits.json').read_text())
lines = ['// Generated by scripts/generate-mech-rigs.py from model manifests and Data/mech-gaits.json.',
         'using Godot;', '', 'namespace Mech;', '',
         '/// <summary>The prepared chassis table, kept off MechModel so rules code can read hardpoints without building meshes.</summary>',
         'internal static class PreparedMechModels', '{',
         '    internal sealed record PreparedModel(string Chassis, MechModel.RigProfile Rig, Hardpoint[] Hardpoints);',
         '    internal static readonly Dictionary<string, PreparedModel> Models = new()', '    {']

def f(value):
    return f'{value:.7f}f'
def vec(value):
    return 'new(' + ', '.join(f(v) for v in value) + ')'
def text(value):
    return 'null' if value is None else f'"{value}"'
def strings(values):
    return '[' + ', '.join(text(v) for v in values) + ']'
def hardpoint(name, info):
    stock = '' if 'stock' not in info else f', {text(info["stock"])}, {text(info["location"] + "_" + info["part"])}, {strings(info["markers"])}'
    return (f'            new("{name}", MechLocation.{info["location"]}, HardpointClass.{info["class"]}, '
            f'{strings(sorted(info["visuals"]))}{stock}),')

prepared = set()
for mech in catalog['Mechs']:
    # Prepared GLBs and manifests are named by the hyphen-free chassis identity, e.g. shadow-hawk -> Shadowhawk.
    chassis = mech['Id'].replace('-', '').capitalize()
    manifest_path = root / 'Assets/Models' / (chassis + '.json')
    if not manifest_path.exists():
        continue
    prepared.add(mech['Id'])
    manifest = json.loads(manifest_path.read_text())
    rig = manifest['rig']
    gait = gaits['tuned'].get(mech['Id'], gaits['default'])
    gait_args = ', '.join(f'{name}: {value}f' for name, value in gait.items())
    lines.append(f'        ["{mech["Id"]}"] = new("{chassis}", new({f(rig["waist"])}, {vec(rig["hip"])}, {vec(rig["knee"])},')
    lines.append(f'            {vec(rig["ankle"])}, {vec(rig["shoulder"])}, new({gait_args})),')
    lines.append('        [')
    lines.extend(hardpoint(name, info) for name, info in manifest['hardpoints'].items())
    lines.append('        ]),')
unknown = set(gaits['tuned']) - prepared
if unknown:
    raise SystemExit(f'Tuned gaits name chassis without prepared models: {", ".join(sorted(unknown))}')
lines.extend(['    };', '',
              '    /// <summary>A chassis\'s hardpoints; empty for generic geometry.</summary>',
              '    public static IReadOnlyList<Hardpoint> Hardpoints(string chassisId) =>',
              '        Models.TryGetValue(chassisId, out var prepared) ? prepared.Hardpoints : [];', '}', ''])
(root / 'Scripts/PreparedMechModels.cs').write_text('\n'.join(lines))
